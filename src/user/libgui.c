gui_window_t* gui_create_window(const char* title, int x, int y, int width, int height)
{
    int win_id = sys_gui_create_win(title, x, y, width, height);
    if (win_id <= 0)
        return NULL;

    uint32_t* buffer = (uint32_t*)sys_gui_map_buffer(win_id);
    if (!buffer)
    {
        sys_gui_destroy_win(win_id);
        return NULL;
    }

    gui_window_t* win = (gui_window_t*)malloc(sizeof(gui_window_t));
    if (!win)
    {
        sys_gui_destroy_win(win_id);
        return NULL;
    }

    win->id       = win_id;
    win->width    = width;
    win->height   = height;
    win->client_w = width - 2;
    win->client_h = height - TITLEBAR_HEIGHT - 2;
    win->buffer   = buffer;
    win->closed   = false;

    return win;
}

void gui_destroy_window(gui_window_t* win)
{
    if (!win) return;
    sys_gui_destroy_win(win->id);
    free(win);
}

bool gui_poll_event(gui_window_t* win, gui_event_t* ev)
{
    if (!win || !ev) return false;
    int res = sys_gui_poll_event(win->id, ev);
    if (res == 1)
    {
        if (ev->type == GUI_EVENT_CLOSE)
            win->closed = true;
        return true;
    }
    return false;
}

void gui_present(gui_window_t* win)
{
    if (!win) return;
    sys_gui_damage(win->id, 0, 0, win->client_w, win->client_h);
}

void gui_damage(gui_window_t* win, int x, int y, int w, int h)
{
    if (!win) return;
    sys_gui_damage(win->id, x, y, w, h);
}

void gui_put_pixel(gui_window_t* win, int x, int y, uint32_t color)
{
    if (!win || !win->buffer) return;
    if (x < 0 || x >= win->client_w || y < 0 || y >= win->client_h) return;
    win->buffer[y * win->client_w + x] = color;
}

uint32_t gui_get_pixel(gui_window_t* win, int x, int y)
{
    if (!win || !win->buffer) return 0;
    if (x < 0 || x >= win->client_w || y < 0 || y >= win->client_h) return 0;
    return win->buffer[y * win->client_w + x];
}

void gui_clear(gui_window_t* win, uint32_t color)
{
    if (!win || !win->buffer) return;
    int total = win->client_w * win->client_h;
    for (int i = 0; i < total; i++)
        win->buffer[i] = color;
}

void gui_draw_line(gui_window_t* win, int x0, int y0, int x1, int y1, uint32_t color)
{
    if (!win || !win->buffer) return;

    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;

    while (true)
    {
        gui_put_pixel(win, x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy)
        {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx)
        {
            err += dx;
            y0 += sy;
        }
    }
}

void gui_draw_rect(gui_window_t* win, int x, int y, int w, int h, uint32_t color)
{
    if (!win || !win->buffer || w <= 0 || h <= 0) return;
    gui_draw_line(win, x, y, x + w - 1, y, color);
    gui_draw_line(win, x, y + h - 1, x + w - 1, y + h - 1, color);
    gui_draw_line(win, x, y, x, y + h - 1, color);
    gui_draw_line(win, x + w - 1, y, x + w - 1, y + h - 1, color);
}

void gui_fill_rect(gui_window_t* win, int x, int y, int w, int h, uint32_t color)
{
    if (!win || !win->buffer || w <= 0 || h <= 0) return;

    int x0 = (x < 0) ? 0 : x;
    int y0 = (y < 0) ? 0 : y;
    int x1 = (x + w > win->client_w) ? win->client_w : (x + w);
    int y1 = (y + h > win->client_h) ? win->client_h : (y + h);

    if (x0 >= x1 || y0 >= y1) return;

    for (int r = y0; r < y1; r++)
    {
        uint32_t* row = &win->buffer[r * win->client_w + x0];
        int count = x1 - x0;
        for (int c = 0; c < count; c++)
            row[c] = color;
    }
}

void gui_draw_circle(gui_window_t* win, int xc, int yc, int r, uint32_t color)
{
    if (!win || !win->buffer) return;
    int x = 0;
    int y = r;
    int d = 3 - 2 * r;

    while (y >= x)
    {
        gui_put_pixel(win, xc + x, yc + y, color);
        gui_put_pixel(win, xc - x, yc + y, color);
        gui_put_pixel(win, xc + x, yc - y, color);
        gui_put_pixel(win, xc - x, yc - y, color);
        gui_put_pixel(win, xc + y, yc + x, color);
        gui_put_pixel(win, xc - y, yc + x, color);
        gui_put_pixel(win, xc + y, yc - x, color);
        gui_put_pixel(win, xc - y, yc - x, color);

        x++;
        if (d > 0)
        {
            y--;
            d = d + 4 * (x - y) + 10;
        }
        else
        {
            d = d + 4 * x + 6;
        }
    }
}

void gui_fill_circle(gui_window_t* win, int xc, int yc, int r, uint32_t color)
{
    if (!win || !win->buffer) return;
    int x = 0;
    int y = r;
    int d = 3 - 2 * r;

    while (y >= x)
    {
        gui_draw_line(win, xc - x, yc + y, xc + x, yc + y, color);
        gui_draw_line(win, xc - x, yc - y, xc + x, yc - y, color);
        gui_draw_line(win, xc - y, yc + x, xc + y, yc + x, color);
        gui_draw_line(win, xc - y, yc - x, xc + y, yc - x, color);

        x++;
        if (d > 0)
        {
            y--;
            d = d + 4 * (x - y) + 10;
        }
        else
        {
            d = d + 4 * x + 6;
        }
    }
}

void gui_draw_char(gui_window_t* win, int x, int y, char c, uint32_t fg, uint32_t bg)
{
    if (!win || !win->buffer) return;
    if (c < 32 || c > 126)
        c = '?';

    const uint8_t* glyph = g_Font8x8[(int)c - 32];
    for (int cy = 0; cy < 8; cy++)
    {
        uint8_t row = glyph[cy];
        for (int cx = 0; cx < 8; cx++)
        {
            if (row & (0x80 >> cx))
            {
                gui_put_pixel(win, x + cx, y + cy, fg);
            }
            else if (bg != GUI_COLOR_TRANSPARENT)
            {
                gui_put_pixel(win, x + cx, y + cy, bg);
            }
        }
    }
}

void gui_draw_text(gui_window_t* win, int x, int y, const char* str, uint32_t fg, uint32_t bg)
{
    if (!win || !win->buffer || !str) return;

    int startX = x;
    while (*str)
    {
        if (*str == '\n')
        {
            y += 10;
            x = startX;
        }
        else if (*str == '\t')
        {
            x += 8 * 4;
        }
        else
        {
            gui_draw_char(win, x, y, *str, fg, bg);
            x += 8;
        }
        str++;
    }
}
