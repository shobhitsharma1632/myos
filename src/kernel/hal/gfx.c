bool GFX_Initialize(uint32_t width, uint32_t height)
{
    if (!BGA_SetVideoMode(width, height, 32))
    {
        log_err(MODULE, "Failed to initialize BGA video mode %ux%u", width, height);
        return false;
    }

    g_Width = width;
    g_Height = height;

    uint32_t bufferSize = width * height * sizeof(uint32_t);
    g_Backbuffer = (uint32_t*)kmalloc(bufferSize);
    if (!g_Backbuffer)
    {
        log_crit(MODULE, "Failed to allocate GFX backbuffer (%u KB)!", bufferSize / 1024);
        return false;
    }

    GFX_ResetClip();
    GFX_Clear(GFX_COLOR_SLATE_BG);
    GFX_SwapBuffers();

    log_info(MODULE, "GFX 2D Engine initialized (%ux%u @ 32bpp, backbuffer: 0x%x).",
             width, height, (uint32_t)g_Backbuffer);
    return true;
}

void GFX_SwapBuffers(void)
{
    void* front = BGA_GetFramebuffer();
    if (!front || !g_Backbuffer) return;

    // Fast copy backbuffer to front video memory
    memcpy(front, g_Backbuffer, g_Width * g_Height * sizeof(uint32_t));
}

uint32_t* GFX_GetBackbuffer(void)
{
    return g_Backbuffer;
}

uint32_t GFX_GetWidth(void)
{
    return g_Width;
}

uint32_t GFX_GetHeight(void)
{
    return g_Height;
}

void GFX_SetClip(int32_t x, int32_t y, int32_t width, int32_t height)
{
    if (x < 0) { width += x; x = 0; }
    if (y < 0) { height += y; y = 0; }
    if (x + width > (int32_t)g_Width) width = g_Width - x;
    if (y + height > (int32_t)g_Height) height = g_Height - y;

    g_ClipRect.x = x;
    g_ClipRect.y = y;
    g_ClipRect.width = (width > 0) ? width : 0;
    g_ClipRect.height = (height > 0) ? height : 0;
}

void GFX_ResetClip(void)
{
    g_ClipRect.x = 0;
    g_ClipRect.y = 0;
    g_ClipRect.width = g_Width;
    g_ClipRect.height = g_Height;
}

void GFX_Clear(uint32_t color)
{
    if (!g_Backbuffer) return;
    uint32_t count = g_Width * g_Height;
    for (uint32_t i = 0; i < count; i++)
    {
        g_Backbuffer[i] = color;
    }
}

void GFX_PutPixel(int32_t x, int32_t y, uint32_t color)
{
    if (x < g_ClipRect.x || x >= g_ClipRect.x + g_ClipRect.width ||
        y < g_ClipRect.y || y >= g_ClipRect.y + g_ClipRect.height)
        return;

    g_Backbuffer[y * g_Width + x] = color;
}

uint32_t GFX_GetPixel(int32_t x, int32_t y)
{
    if (x < 0 || x >= (int32_t)g_Width || y < 0 || y >= (int32_t)g_Height)
        return 0;
    return g_Backbuffer[y * g_Width + x];
}

void GFX_FillRect(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color)
{
    if (w <= 0 || h <= 0) return;

    int32_t x1 = x;
    int32_t y1 = y;
    int32_t x2 = x + w;
    int32_t y2 = y + h;

    // Intersect with clip rect
    if (x1 < g_ClipRect.x) x1 = g_ClipRect.x;
    if (y1 < g_ClipRect.y) y1 = g_ClipRect.y;
    if (x2 > g_ClipRect.x + g_ClipRect.width) x2 = g_ClipRect.x + g_ClipRect.width;
    if (y2 > g_ClipRect.y + g_ClipRect.height) y2 = g_ClipRect.y + g_ClipRect.height;

    if (x1 >= x2 || y1 >= y2) return;

    for (int32_t cy = y1; cy < y2; cy++)
    {
        uint32_t* row = &g_Backbuffer[cy * g_Width + x1];
        int32_t span = x2 - x1;
        for (int32_t cx = 0; cx < span; cx++)
        {
            row[cx] = color;
        }
    }
}

void GFX_DrawRect(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color)
{
    if (w <= 0 || h <= 0) return;
    GFX_FillRect(x, y, w, 1, color);             // Top
    GFX_FillRect(x, y + h - 1, w, 1, color);     // Bottom
    GFX_FillRect(x, y, 1, h, color);             // Left
    GFX_FillRect(x + w - 1, y, 1, h, color);     // Right
}

void GFX_DrawLine(int32_t x0, int32_t y0, int32_t x1, int32_t y1, uint32_t color)
{
    int32_t dx = (x1 >= x0) ? (x1 - x0) : (x0 - x1);
    int32_t dy = (y1 >= y0) ? (y1 - y0) : (y0 - y1);
    int32_t sx = (x0 < x1) ? 1 : -1;
    int32_t sy = (y0 < y1) ? 1 : -1;
    int32_t err = dx - dy;

    while (true)
    {
        GFX_PutPixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int32_t e2 = 2 * err;
        if (e2 > -dy)
        {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx)
        {
            err += dx;
            y0 += sy;
        }
    }
}

void GFX_DrawCircle(int32_t xc, int32_t yc, int32_t r, uint32_t color)
{
    int32_t x = 0;
    int32_t y = r;
    int32_t d = 3 - 2 * r;

    while (y >= x)
    {
        GFX_PutPixel(xc + x, yc + y, color);
        GFX_PutPixel(xc - x, yc + y, color);
        GFX_PutPixel(xc + x, yc - y, color);
        GFX_PutPixel(xc - x, yc - y, color);
        GFX_PutPixel(xc + y, yc + x, color);
        GFX_PutPixel(xc - y, yc + x, color);
        GFX_PutPixel(xc + y, yc - x, color);
        GFX_PutPixel(xc - y, yc - x, color);

        x++;
        if (d > 0)
        {
            y--;
            d = d + 4 * (x - y) + 10;
        }
        else
        {
            d = d + 4 * x + 6;
        }
    }
}

void GFX_FillCircle(int32_t xc, int32_t yc, int32_t r, uint32_t color)
{
    int32_t x = 0;
    int32_t y = r;
    int32_t d = 3 - 2 * r;

    while (y >= x)
    {
        GFX_DrawLine(xc - x, yc + y, xc + x, yc + y, color);
        GFX_DrawLine(xc - x, yc - y, xc + x, yc - y, color);
        GFX_DrawLine(xc - y, yc + x, xc + y, yc + x, color);
        GFX_DrawLine(xc - y, yc - x, xc + y, yc - x, color);

        x++;
        if (d > 0)
        {
            y--;
            d = d + 4 * (x - y) + 10;
        }
        else
        {
            d = d + 4 * x + 6;
        }
    }
}

void GFX_DrawChar(int32_t x, int32_t y, char c, uint32_t fgColor, uint32_t bgColor)
{
    if (c < 32 || c > 126)
        c = '?';

    const uint8_t* glyph = g_Font8x8[(int)c - 32];

    for (int cy = 0; cy < 8; cy++)
    {
        uint8_t row = glyph[cy];
        for (int cx = 0; cx < 8; cx++)
        {
            if (row & (0x80 >> cx))
            {
                GFX_PutPixel(x + cx, y + cy, fgColor);
            }
            else if (bgColor != GFX_COLOR_TRANSPARENT)
            {
                GFX_PutPixel(x + cx, y + cy, bgColor);
            }
        }
    }
}

void GFX_DrawString(int32_t x, int32_t y, const char* str, uint32_t fgColor, uint32_t bgColor)
{
    if (!str) return;

    int32_t startX = x;
    while (*str)
    {
        if (*str == '\n')
        {
            y += 10;
            x = startX;
        }
        else if (*str == '\t')
        {
            x += 8 * 4;
        }
        else
        {
            GFX_DrawChar(x, y, *str, fgColor, bgColor);
            x += 8;
        }
        str++;
    }
}

void GFX_BlitBuffer(int32_t destX, int32_t destY, const uint32_t* srcBuffer, int32_t srcWidth, int32_t srcHeight)
{
    if (!g_Backbuffer || !srcBuffer || srcWidth <= 0 || srcHeight <= 0) return;

    int32_t x0 = destX;
    int32_t y0 = destY;
    int32_t x1 = destX + srcWidth;
    int32_t y1 = destY + srcHeight;

    int32_t clip_x0 = g_ClipRect.x;
    int32_t clip_y0 = g_ClipRect.y;
    int32_t clip_x1 = g_ClipRect.x + g_ClipRect.width;
    int32_t clip_y1 = g_ClipRect.y + g_ClipRect.height;

    if (x0 < clip_x0) x0 = clip_x0;
    if (y0 < clip_y0) y0 = clip_y0;
    if (x1 > clip_x1) x1 = clip_x1;
    if (y1 > clip_y1) y1 = clip_y1;

    if (x0 >= x1 || y0 >= y1) return;

    for (int32_t y = y0; y < y1; y++)
    {
        int32_t srcY = y - destY;
        int32_t srcX = x0 - destX;
        int32_t copyWidth = x1 - x0;

        uint32_t* dst = &g_Backbuffer[y * g_Width + x0];
        const uint32_t* src = &srcBuffer[srcY * srcWidth + srcX];
        memcpy(dst, src, copyWidth * sizeof(uint32_t));
    }
}

void GFX_DrawCursor(int32_t x, int32_t y)
{
    for (int cy = 0; cy < 18; cy++)
    {
        uint16_t mask = g_CursorMask[cy];
        uint16_t fill = g_CursorFill[cy];

        for (int cx = 0; cx < 12; cx++)
        {
            uint16_t bit = 0x800 >> cx;
            if (mask & bit)
            {
                if (fill & bit)
                    GFX_PutPixel(x + cx, y + cy, GFX_COLOR_WHITE);
                else
                    GFX_PutPixel(x + cx, y + cy, GFX_COLOR_BLACK);
            }
        }
    }
}
